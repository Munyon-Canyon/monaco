#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/../apps/backend"
ref=../../docs/reference
bin="$(mktemp -d)"
trap 'rm -rf "$bin"' EXIT
go build -o "$bin/monacoctl" ./cmd/monacoctl

page() {
  local title=$1 topic=$2 source=$3
  {
    printf '# %s\n\nGenerated by `monacoctl docs %s` from %s. Do not edit; run `just gen docs`.\n\n' "$title" "$topic" "$source"
    "$bin/monacoctl" docs "$topic"
  } > "$ref/$topic.md"
}

"$bin/monacoctl" docs events > "$ref/events.md"
page "Flows" flows '`apps/backend/flows.tsv`'
page "Error codes" errors 'the `internal/errs` code table'
page "Log messages" logs 'the `internal/platform/observability` message registry'
echo "wrote $ref/{events,flows,errors,logs}.md"

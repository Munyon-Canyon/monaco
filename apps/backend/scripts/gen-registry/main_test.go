func TestGenerate_writesOneCompanionPerRegistrationFileAndDropsStaleOnes(t *testing.T) {
	t.Parallel()
	root := sampleTree(t)
	for range 2 {
		if err := generate(root); err != nil {
			t.Fatal(err)
		}
	}
	for rel, want := range map[string]string{
		"internal/platform/observability/msgs_boot.gen.go": header + "\npackage observability\n\n" +
			"func init() {\n\tregister(\n\t\tBootA,\n\t\tBootB,\n\t)\n}\n",
		"cmd/monacoctl/report.gen.go": header + "\npackage main\n\n" +
			"func init() {\n\tregisterTool(\"test-report\", toolTestReport)\n}\n",
		"cmd/api/module_alpha.gen.go":       moduleAlpha,
		"cmd/monacoctl/module_alpha.gen.go": moduleAlpha,
		"cmd/worker/module_alpha.gen.go":    moduleAlpha,
		"cmd/api/module_gamma.gen.go":       strings.ReplaceAll(moduleAlpha, "alpha", "gamma"),
		"cmd/monacoctl/module_gamma.gen.go": moduleGammaTool,
	} {
		if got := read(t, root, rel); got != want {
			t.Errorf("%s =\n%s\nwant\n%s", rel, got, want)
		}
	}
	for _, rel := range []string{
		"internal/platform/observability/msgs_none.gen.go", "cmd/monacoctl/plain.gen.go",
		"cmd/worker/module_beta.gen.go", "cmd/worker/consumers_gone.gen.go", "cmd/api/module_gone.gen.go",
	} {
		if _, err := os.Stat(filepath.Join(root, rel)); !os.IsNotExist(err) {
			t.Errorf("%s exists (%v), want no companion", rel, err)
		}
	}
	if read(t, root, "cmd/worker/api.gen.go") == "" {
		t.Error("removed a generated file another generator owns")
	}
	if got, err := drift(root); err != nil || len(got) != 0 {
		t.Fatalf("drift after generate = %v, %v, want none", got, err)
	}
}

func TestDrift_namesHandEditedMissingAndStaleCompanions(t *testing.T) {
	t.Parallel()
	root := sampleTree(t)
	if err := generate(root); err != nil {
		t.Fatal(err)
	}
	edits := map[string]string{
		"cmd/monacoctl/report.gen.go":                "hand edit\n",
		"internal/platform/observability/msgs_db.go": "package observability\n\nvar DBX = Msg{Name: \"db.x\"}\n",
		"cmd/worker/consumers_old.gen.go":            header + "\npackage main\n",
	}
	for rel, body := range edits {
		if err := os.WriteFile(filepath.Join(root, rel), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := drift(root)
	want := []string{
		"cmd/monacoctl/report.gen.go",
		"internal/platform/observability/msgs_db.gen.go",
		"cmd/worker/consumers_old.gen.go (stale)",
	}
	if err != nil || !slices.Equal(got, want) {
		t.Fatalf("drift = %q, %v, want %q", got, err, want)
	}
}


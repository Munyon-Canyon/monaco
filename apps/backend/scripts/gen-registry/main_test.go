func TestMain_generatesInTheWorkingDirOrExitsOneNamingTheError(t *testing.T) {
	t.Parallel()
	root := sampleTree(t)
	cmd := testkit.MainCommand(t, nil)
	cmd.Dir = root
	if out, err := cmd.CombinedOutput(); err != nil || len(out) != 0 {
		t.Fatalf("gen-registry in %s = %v %q", root, err, out)
	}
	if got, err := drift(root); err != nil || len(got) != 0 {
		t.Fatalf("drift after running main = %v, %v", got, err)
	}
	failing := testkit.MainCommand(t, nil, filepath.Join(root, "missing"))
	out, _ := failing.CombinedOutput()
	if code := failing.ProcessState.ExitCode(); code != 1 ||
		!strings.HasPrefix(string(out), "gen-registry: read go.mod: ") {
		t.Fatalf("gen-registry on a missing dir = %d %q", code, out)
	}
}

const flowScriptsF01a = header + "\npackage flows\n\n" +
	"func (defined) ScriptsF01a() map[string]Script {\n\treturn map[string]Script{\n" +
	"\t\t\"F01aSetHandleOK\":    F01aSetHandleOK,\n\t\t\"F01aSetHandleTaken\": F01aSetHandleTaken,\n\t}\n}\n"

func TestGenerate_writesOneScriptsCompanionPerFlowFile(t *testing.T) {
	t.Parallel()
	for name, tc := range map[string]struct {
		files   map[string]string
		want    map[string]string
		missing []string
	}{
		"a flow file gets its scripts": {
			files: map[string]string{
				"internal/testkit/flows/f01a.go": "package flows\n\n" +
					"func F01aSetHandleOK(s *scenario.Scenario) {}\n" +
					"func F01aSetHandleTaken(*scenario.Scenario) {}\n" +
					"func f01aHelper(s *scenario.Scenario) {}\n" +
					"func (defined) F01aMethod(s *scenario.Scenario) {}\n",
			},
			want: map[string]string{"internal/testkit/flows/f01a.gen.go": flowScriptsF01a},
		},
		"a file with no scripts gets no companion": {
			files: map[string]string{
				"internal/testkit/flows/scripts.go":  "package flows\n\nfunc Scripts() {}\n",
				"internal/testkit/flows/f02_test.go": "package flows\n\nfunc F02X(s *scenario.Scenario) {}\n",
			},
			missing: []string{"internal/testkit/flows/scripts.gen.go", "internal/testkit/flows/f02_test.gen.go"},
		},
		"a companion whose flow file is gone is removed": {
			files: map[string]string{
				"internal/testkit/flows/f09.gen.go":   header + "\npackage flows\n",
				"internal/testkit/flows/other.gen.go": "// Code generated by another tool. DO NOT EDIT.\n",
			},
			want:    map[string]string{"internal/testkit/flows/other.gen.go": "// Code generated by another tool. DO NOT EDIT.\n"},
			missing: []string{"internal/testkit/flows/f09.gen.go"},
		},
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			tc.files["go.mod"] = "module m\n"
			root := writeTree(t, tc.files)
			if err := generate(root); err != nil {
				t.Fatal(err)
			}
			expectFiles(t, root, tc.want, tc.missing)
		})
	}
}

func expectFiles(t *testing.T, root string, want map[string]string, missing []string) {
	t.Helper()
	for rel, body := range want {
		if got := read(t, root, rel); got != body {
			t.Errorf("%s =\n%s\nwant\n%s", rel, got, body)
		}
	}
	for _, rel := range missing {
		if _, err := os.Stat(filepath.Join(root, rel)); !os.IsNotExist(err) {
			t.Errorf("%s exists (%v), want no companion", rel, err)
		}
	}
}

func TestGenerate_rejectsAFlowScriptNameWithTheWrongSignature(t *testing.T) {
	t.Parallel()
	const want = "internal/testkit/flows/f01.go: F01Bad is named like a flow script but is not func(*scenario.Scenario)"
	for name, decl := range map[string]string{
		"an int parameter":       "func F01Bad(n int) {}",
		"two parameters":         "func F01Bad(a, b *scenario.Scenario) {}",
		"a result":               "func F01Bad(s *scenario.Scenario) error { return nil }",
		"a value parameter":      "func F01Bad(s scenario.Scenario) {}",
		"another package":        "func F01Bad(s *other.Scenario) {}",
		"another scenario type":  "func F01Bad(s *scenario.Step) {}",
		"an unqualified pointer": "func F01Bad(s *Scenario) {}",
		"no parameters":          "func F01Bad() {}",
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			root := writeTree(t, map[string]string{
				"go.mod":                        "module m\n",
				"internal/testkit/flows/f01.go": "package flows\n\n" + decl + "\n",
			})
			if err := generate(root); err == nil || err.Error() != want {
				t.Fatalf("generate = %v, want %q", err, want)
			}
		})
	}
}


package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"maps"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"unicode"

	"golang.org/x/mod/modfile"
)

const (
	header      = "// Code generated by scripts/gen-registry. DO NOT EDIT.\n"
	msgsDir     = "internal/platform/observability"
	toolsDir    = "cmd/monacoctl"
	workerDir   = "cmd/worker"
	modulesDir  = "internal/modules"
	genSuffix   = ".gen.go"
	testSuffix  = "_test.go"
	toolPattern = `^tool[A-Z]\w*$`
)

type plan map[string][]byte

func main() {
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	if err := generate(root); err != nil {
		_, _ = fmt.Fprintf(os.Stderr, "gen-registry: %v\n", err)
		os.Exit(1)
	}
}

func generate(root string) error {
	want, err := build(root)
	if err != nil {
		return err
	}
	stale, err := owned(root)
	if err != nil {
		return err
	}
	for _, rel := range stale {
		if _, keep := want[rel]; !keep {
			if err := os.Remove(filepath.Join(root, rel)); err != nil {
				return fmt.Errorf("remove stale %s: %w", rel, err)
			}
		}
	}
	for _, rel := range slices.Sorted(maps.Keys(want)) {
		path := filepath.Join(root, rel)
		if cur, err := os.ReadFile(path); err == nil && bytes.Equal(cur, want[rel]) {
			continue
		}
		if err := os.WriteFile(path, want[rel], 0o644); err != nil {
			return fmt.Errorf("write %s: %w", rel, err)
		}
	}
	return nil
}

func drift(root string) ([]string, error) {
	want, err := build(root)
	if err != nil {
		return nil, err
	}
	have, err := owned(root)
	if err != nil {
		return nil, err
	}
	var out []string
	for _, rel := range slices.Sorted(maps.Keys(want)) {
		if cur, err := os.ReadFile(filepath.Join(root, rel)); err != nil || !bytes.Equal(cur, want[rel]) {
			out = append(out, rel)
		}
	}
	for _, rel := range have {
		if _, ok := want[rel]; !ok {
			out = append(out, rel+" (stale)")
		}
	}
	return out, nil
}

func build(root string) (plan, error) {
	p := plan{}
	for _, step := range []func(string, plan) error{planMsgs, planTools, planConsumers} {
		if err := step(root, p); err != nil {
			return nil, err
		}
	}
	return p, nil
}

func owned(root string) ([]string, error) {
	var out []string
	for _, dir := range []string{msgsDir, toolsDir, workerDir} {
		names, err := list(root, dir, func(name string) bool { return strings.HasSuffix(name, genSuffix) })
		if err != nil {
			return nil, err
		}
		for _, rel := range names {
			b, err := os.ReadFile(filepath.Join(root, rel))
			if err != nil {
				return nil, fmt.Errorf("read %s: %w", rel, err)
			}
			if bytes.HasPrefix(b, []byte(header)) {
				out = append(out, rel)
			}
		}
	}
	return out, nil
}

func list(root, dir string, match func(string) bool) ([]string, error) {
	entries, err := os.ReadDir(filepath.Join(root, dir))
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("list %s: %w", dir, err)
	}
	var out []string
	for _, e := range entries {
		if match(e.Name()) {
			out = append(out, filepath.Join(dir, e.Name()))
		}
	}
	return out, nil
}

func sources(root, dir, prefix string) ([]*ast.File, []string, error) {
	names, err := list(root, dir, func(name string) bool {
		return strings.HasPrefix(name, prefix) && strings.HasSuffix(name, ".go") &&
			!strings.HasSuffix(name, testSuffix) && !strings.HasSuffix(name, genSuffix)
	})
	if err != nil {
		return nil, nil, err
	}
	files := make([]*ast.File, 0, len(names))
	for _, rel := range names {
		f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(root, rel), nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, nil, fmt.Errorf("parse %w", err)
		}
		files = append(files, f)
	}
	return files, names, nil
}

func planMsgs(root string, p plan) error {
	files, names, err := sources(root, msgsDir, "msgs_")
	if err != nil {
		return err
	}
	for i, f := range files {
		vars := msgVars(f)
		if len(vars) == 0 {
			continue
		}
		body := "func init() {\n\tregister(\n\t\t" + strings.Join(vars, ",\n\t\t") + ",\n\t)\n}\n"
		p.add(companion(names[i]), f.Name.Name, nil, body)
	}
	return nil
}

func msgVars(f *ast.File) []string {
	var vars []string
	for _, decl := range f.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.VAR {
			continue
		}
		for _, spec := range gen.Specs {
			vs := spec.(*ast.ValueSpec)
			for j, name := range vs.Names {
				if j < len(vs.Values) && isMsgLiteral(vs.Values[j]) {
					vars = append(vars, name.Name)
				}
			}
		}
	}
	return vars
}

func isMsgLiteral(e ast.Expr) bool {
	lit, ok := e.(*ast.CompositeLit)
	if !ok {
		return false
	}
	id, ok := lit.Type.(*ast.Ident)
	return ok && id.Name == "Msg"
}

func planTools(root string, p plan) error {
	files, names, err := sources(root, toolsDir, "")
	if err != nil {
		return err
	}
	pattern := regexp.MustCompile(toolPattern)
	seen := map[string]string{}
	for i, f := range files {
		var body strings.Builder
		for _, decl := range f.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Recv != nil || !pattern.MatchString(fn.Name.Name) || !isToolFactory(fn.Type) {
				continue
			}
			name := kebab(strings.TrimPrefix(fn.Name.Name, "tool"))
			if other, dup := seen[name]; dup {
				return fmt.Errorf("tool %q is declared by both %s and %s", name, other, fn.Name.Name)
			}
			seen[name] = fn.Name.Name
			fmt.Fprintf(&body, "\tregisterTool(%s, %s)\n", strconv.Quote(name), fn.Name.Name)
		}
		if body.Len() == 0 {
			continue
		}
		p.add(companion(names[i]), f.Name.Name, nil, "func init() {\n"+body.String()+"}\n")
	}
	return nil
}

func isToolFactory(t *ast.FuncType) bool {
	params, results := t.Params.List, t.Results
	return len(params) == 1 && len(params[0].Names) <= 1 && isIdent(params[0].Type, "toolEnv") &&
		results != nil && len(results.List) == 1 && len(results.List[0].Names) == 0 && isIdent(results.List[0].Type, "tool")
}

func isIdent(e ast.Expr, name string) bool {
	id, ok := e.(*ast.Ident)
	return ok && id.Name == name
}

func kebab(s string) string {
	var b strings.Builder
	for i, r := range s {
		if unicode.IsUpper(r) {
			if i > 0 {
				b.WriteByte('-')
			}
			r = unicode.ToLower(r)
		}
		b.WriteRune(r)
	}
	return b.String()
}

func planConsumers(root string, p plan) error {
	mod, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return fmt.Errorf("read go.mod: %w", err)
	}
	entries, err := os.ReadDir(filepath.Join(root, modulesDir))
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("list modules: %w", err)
	}
	for _, e := range entries {
		if e.IsDir() {
			if err := planModule(root, modfile.ModulePath(mod), e.Name(), p); err != nil {
				return err
			}
		}
	}
	return nil
}

func planModule(root, modPath, name string, p plan) error {
	files, _, err := sources(root, filepath.Join(modulesDir, name), "")
	if err != nil {
		return err
	}
	if !slices.ContainsFunc(files, declaresConsumers) {
		return nil
	}
	imports := []string{"module " + strconv.Quote(modPath+"/"+modulesDir+"/"+name)}
	body := "func init() {\n\tregistered.add(module.Consumers)\n}\n"
	p.add(filepath.Join(workerDir, "consumers_"+name+genSuffix), "main", imports, body)
	return nil
}

func declaresConsumers(f *ast.File) bool {
	return slices.ContainsFunc(f.Decls, func(d ast.Decl) bool {
		fn, ok := d.(*ast.FuncDecl)
		return ok && fn.Recv == nil && fn.Name.Name == "Consumers"
	})
}

func companion(rel string) string {
	return strings.TrimSuffix(rel, ".go") + genSuffix
}

func (p plan) add(rel, pkg string, imports []string, body string) {
	src := header + "\npackage " + pkg + "\n\n"
	if len(imports) > 0 {
		src += "import (\n\t" + strings.Join(imports, "\n\t") + "\n)\n\n"
	}
	p[rel] = []byte(src + body)
}

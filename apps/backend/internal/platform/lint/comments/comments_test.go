func TestRun_allowsOnlyGoDirectivesAndGeneratedFiles(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name     string
		file     string
		src      string
		wantCode int
		wantOut  string
	}{
		{
			name: "go generate directive allowed",
			file: "gen.go",
			src:  "package p\n\n//go:generate echo hi\n",
		},
		{
			name: "go build constraint allowed",
			file: "build.go",
			src:  "//go:build linux\n\npackage p\n",
		},
		{
			name: "generated file allowed",
			file: "zz_generated.go",
			src:  "// Code generated by sqlc. DO NOT EDIT.\n\npackage p\n\n// Get returns a row.\nfunc Get() {}\n",
		},
		{
			name:     "doc comment rejected",
			file:     "doc.go",
			src:      "package p\n\n// Get returns a row.\nfunc Get() {}\n",
			wantCode: 1,
			wantOut:  "$F:3: comment not allowed\n",
		},
		{
			name:     "todo rejected",
			file:     "todo.go",
			src:      "package p\n\nfunc Get() {\n\t// TODO handle errors\n}\n",
			wantCode: 1,
			wantOut:  "$F:4: comment not allowed\n",
		},
		{
			name:     "nolint rejected",
			file:     "nolint.go",
			src:      "package p\n\nvar x = 1 //nolint:gochecknoglobals\n",
			wantCode: 1,
			wantOut:  "$F:3: comment not allowed\n",
		},
		{
			name:     "block comment rejected",
			file:     "block.go",
			src:      "package p\n\n/* Get\nreturns a row. */\nfunc Get() {}\n",
			wantCode: 1,
			wantOut:  "$F:3: comment not allowed\n",
		},
		{
			name:     "comment in test file rejected",
			file:     "p_test.go",
			src:      "package p\n\nimport \"testing\"\n\nfunc TestGet(t *testing.T) {\n\t// hi\n}\n",
			wantCode: 1,
			wantOut:  "$F:6: comment not allowed\n",
		},
		{
			name:     "every comment in a file reported in line order",
			file:     "many.go",
			src:      "// Package p.\npackage p\n\n//go:generate echo hi\n\n// A.\nvar A = 1 // one\n",
			wantCode: 1,
			wantOut:  "$F:1: comment not allowed\n$F:6: comment not allowed\n$F:7: comment not allowed\n",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			dir := t.TempDir()
			path := writeFile(t, dir, tc.file, tc.src)

			code, stdout, stderr := run(path)

			if code != tc.wantCode {
				t.Fatalf("exit code = %d, want %d (stderr %q)", code, tc.wantCode, stderr)
			}
			if want := strings.ReplaceAll(tc.wantOut, "$F", path); stdout != want {
				t.Fatalf("stdout = %q, want %q", stdout, want)
			}
			if stderr != "" {
				t.Fatalf("stderr = %q, want empty", stderr)
			}
		})
	}
}

func TestRun_recursivePatternSkipsTestdataHiddenAndUnderscoreDirs(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	bad := "package p\n\n// hi\n"
	writeFile(t, dir, "a/ok.go", "package a\n")
	writeFile(t, dir, "a/b/bad.go", bad)
	writeFile(t, dir, "a/notes.txt", "// not go\n")
	writeFile(t, dir, "a/testdata/bad.go", bad)
	writeFile(t, dir, "a/.hidden/bad.go", bad)
	writeFile(t, dir, "a/_skip/bad.go", bad)

	code, stdout, stderr := run(filepath.Join(dir, "a") + "/...")

	if code != 1 || stderr != "" {
		t.Fatalf("exit code = %d stderr = %q, want 1 and empty", code, stderr)
	}
	if want := filepath.Join(dir, "a/b/bad.go") + ":3: comment not allowed\n"; stdout != want {
		t.Fatalf("stdout = %q, want %q", stdout, want)
	}
}

func TestRun_directoryArgumentChecksOnlyItsOwnFiles(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	writeFile(t, dir, "ok.go", "package p\n")
	writeFile(t, dir, "sub/bad.go", "package sub\n\n// hi\n")

	code, stdout, stderr := run(dir)

	if code != 0 || stdout != "" || stderr != "" {
		t.Fatalf("exit=%d stdout=%q stderr=%q, want 0 and no output", code, stdout, stderr)
	}
}

func TestRun_reportsUnreadableInputOnStderrWithExit2(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	for _, tc := range []struct {
		name string
		arg  string
	}{
		{"missing path", filepath.Join(dir, "missing.go")},
		{"syntax error", writeFile(t, dir, "broken.go", "package p\n\nfunc {\n")},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			code, stdout, stderr := run(tc.arg)
			if code != 2 || stdout != "" || stderr == "" {
				t.Fatalf("exit=%d stdout=%q stderr=%q, want 2, no stdout, an error", code, stdout, stderr)
			}
		})
	}
}

func run(args ...string) (int, string, string) {
	var stdout, stderr bytes.Buffer
	code := comments.Run(args, &stdout, &stderr)
	return code, stdout.String(), stderr.String()
}

func writeFile(t *testing.T, dir, name, src string) string {
	t.Helper()
	path := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

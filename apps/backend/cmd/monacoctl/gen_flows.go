package main

import (
	"fmt"
	"io"
	"io/fs"
	"os"
	"path"
	"regexp"
	"strings"

	"github.com/monaco/monaco/apps/backend/internal/errs"
	"github.com/monaco/monaco/apps/backend/internal/tools/flows"
)

const (
	flowsSwiftDir    = "packages/flows/Sources/MonacoFlows"
	flowsSwiftHeader = "// Code generated by monacoctl gen flows from apps/backend/flows.tsv. DO NOT EDIT.\n"
)

var flowSwiftFile = regexp.MustCompile(`^Flow([0-9]+[a-z]?)\.gen\.swift$`)

func runGenFlows(root string, stdout, stderr io.Writer) int {
	parsed, err := readFlowsTSV(os.DirFS(root))
	if err == nil {
		err = writeFlowsSwift(root, parsed)
	}
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "monacoctl: %v\n", err)
		return 1
	}
	_, _ = fmt.Fprintf(stdout, "wrote %d flow outcome enums to %s\n", len(parsed), flowsSwiftDir)
	return 0
}

func readFlowsTSV(repo fs.FS) ([]flows.Flow, error) {
	parsed, problems, err := readFlows(repo)
	if err == nil && len(problems) > 0 {
		err = errs.New(errs.CodeInvalidInput, "monacoctl.readFlowsTSV: "+problems[0].String())
	}
	return parsed, err
}

func writeFlowsSwift(root string, parsed []flows.Flow) error {
	dir, err := os.OpenRoot(root)
	if err != nil {
		return errs.Wrap(err, errs.CodeInvalidInput, "monacoctl.writeFlowsSwift")
	}
	defer func() { _ = dir.Close() }()
	if err := dir.MkdirAll(flowsSwiftDir, 0o750); err != nil {
		return errs.Wrap(err, errs.CodeInternal, "monacoctl.writeFlowsSwift")
	}
	keep := map[string]bool{}
	for _, f := range parsed {
		body, err := renderFlowSwift(f)
		if err != nil {
			return err
		}
		name := "Flow" + f.ID + ".gen.swift"
		keep[name] = true
		if err := dir.WriteFile(path.Join(flowsSwiftDir, name), []byte(body), 0o600); err != nil {
			return errs.Wrap(err, errs.CodeInternal, "monacoctl.writeFlowsSwift")
		}
	}
	return pruneFlowsSwift(dir, keep)
}

func pruneFlowsSwift(dir *os.Root, keep map[string]bool) error {
	entries, _ := fs.ReadDir(dir.FS(), flowsSwiftDir)
	for _, e := range entries {
		if flowSwiftFile.MatchString(e.Name()) && !keep[e.Name()] {
			if err := dir.Remove(path.Join(flowsSwiftDir, e.Name())); err != nil {
				return errs.Wrap(err, errs.CodeInternal, "monacoctl.pruneFlowsSwift")
			}
		}
	}
	return nil
}

type swiftOutcome struct {
	name string
	code string
}

func flowOutcomes(f flows.Flow) ([]swiftOutcome, error) {
	codes := map[string]errs.Code{}
	for _, c := range errs.All() {
		codes[errs.Name(c)] = c
	}
	var (
		out         []swiftOutcome
		interrupted bool
	)
	for _, o := range f.Outcomes {
		if _, crash := o.CrashPoint(); crash {
			interrupted = true
			continue
		}
		if o == flows.OutcomeOK {
			out = append(out, swiftOutcome{name: "ok"})
			continue
		}
		code, ok := codes[string(o)]
		if !ok {
			return nil, errs.New(errs.CodeInvalidInput,
				fmt.Sprintf("monacoctl.flowOutcomes: flow %s outcome %s is not an errs code name", f.ID, o))
		}
		out = append(out, swiftOutcome{name: flowCaseName(string(o)), code: string(code)})
	}
	if interrupted {
		out = append(out, swiftOutcome{name: "interrupted"})
	}
	return out, nil
}

func flowCaseName(outcome string) string {
	name := strings.ToLower(outcome[:1]) + outcome[1:]
	if isSwiftKeyword(name) {
		return "`" + name + "`"
	}
	return name
}

func renderFlowSwift(f flows.Flow) (string, error) {
	outcomes, err := flowOutcomes(f)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(flowsSwiftHeader + "\n")
	b.WriteString("public enum Flow" + f.ID + "Outcome: Sendable, Hashable, CaseIterable {\n")
	writeSwiftCaseList(&b, outcomes)
	b.WriteString("\n    public static let flowID = " + swiftString(f.ID) + "\n")
	commands := make([]string, len(f.Commands))
	for i, c := range f.Commands {
		commands[i] = swiftString(c)
	}
	b.WriteString("    public static let commands: [String] = [" + strings.Join(commands, ", ") + "]\n")
	b.WriteString("\n    public var code: String? {\n        switch self {\n")
	var silent []string
	for _, o := range outcomes {
		if o.code == "" {
			silent = append(silent, "."+o.name)
		}
	}
	if len(silent) > 0 {
		b.WriteString("        case " + strings.Join(silent, ", ") + ": nil\n")
	}
	for _, o := range outcomes {
		if o.code != "" {
			b.WriteString("        case ." + o.name + ": " + swiftString(o.code) + "\n")
		}
	}
	b.WriteString("        }\n    }\n\n    public init?(code: String) {\n        switch code {\n")
	for _, o := range outcomes {
		if o.code != "" {
			b.WriteString("        case " + swiftString(o.code) + ": self = ." + o.name + "\n")
		}
	}
	b.WriteString("        default: return nil\n        }\n    }\n}\n")
	return b.String(), nil
}

func writeSwiftCaseList(b *strings.Builder, outcomes []swiftOutcome) {
	line := "    case"
	for i, o := range outcomes {
		item := " " + o.name
		if i < len(outcomes)-1 {
			item += ","
		}
		if len(line)+len(item) > swiftLineWidth {
			b.WriteString(line + "\n")
			line = "        "
			item = strings.TrimPrefix(item, " ")
		}
		line += item
	}
	b.WriteString(line + "\n")
}

func swiftString(s string) string { return `"` + s + `"` }

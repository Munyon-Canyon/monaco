package main

import (
	"fmt"
	"io"
	"io/fs"
	"os"
	"path"
	"regexp"
	"slices"
	"strings"
	"unicode"

	"github.com/monaco/monaco/apps/backend/internal/errs"
	"github.com/monaco/monaco/apps/backend/internal/tools/flows"
)

const (
	flowsSwiftDir       = "packages/flows/Sources/MonacoFlows"
	flowsSwiftHeader    = "// Code generated by monacoctl gen flows from apps/backend/flows.tsv. DO NOT EDIT.\n"
	scenariosHeader     = "// Code generated by monacoctl gen flows from apps/backend/flows.tsv and packages/flows/app. DO NOT EDIT.\n"
	scenarioManifest    = "scripts/qa/sample-screens.txt"
	scenarioBlockBegin  = "# BEGIN generated flow scenarios"
	scenarioBlockEnd    = "# END generated flow scenarios"
	scenarioLaunchFlag  = "-MonacoFlow"
	scenarioNameColumns = 30
)

var flowSwiftFile = regexp.MustCompile(`^Flow[0-9]+[a-z]?(Scenarios)?\.gen\.swift$`)

func runGenFlows(root string, stdout, stderr io.Writer) int {
	files, err := renderFlows(os.DirFS(root))
	if err == nil {
		err = writeFlowFiles(root, files)
	}
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "monacoctl: %v\n", err)
		return 1
	}
	_, _ = fmt.Fprintf(stdout, "wrote %d flow files to %s and the %s scenario block\n",
		len(files)-1, flowsSwiftDir, scenarioManifest)
	return 0
}

func renderFlows(repo fs.FS) (map[string]string, error) {
	parsed, err := readFlowsTSV(repo)
	if err != nil {
		return nil, err
	}
	built, err := readBuiltFlows(repo)
	if err != nil {
		return nil, err
	}
	manifest, err := fs.ReadFile(repo, scenarioManifest)
	if err != nil {
		return nil, errs.Wrap(err, errs.CodeInvalidInput, "monacoctl.renderFlows")
	}
	files := map[string]string{}
	block := []string{
		scenarioBlockBegin,
		"# monacoctl gen flows writes this block from apps/backend/flows.tsv and packages/flows/app. Never edit it.",
	}
	for _, f := range parsed {
		outcomes, err := flowOutcomes(f)
		if err != nil {
			return nil, err
		}
		files[path.Join(flowsSwiftDir, "Flow"+f.ID+".gen.swift")] = renderFlowSwift(f, outcomes)
		scenarios := slices.DeleteFunc(outcomes, func(o swiftOutcome) bool { return o.name == "ok" })
		if !built[f.ID] || len(scenarios) == 0 {
			continue
		}
		files[path.Join(flowsSwiftDir, "Flow"+f.ID+"Scenarios.gen.swift")] = renderFlowScenariosSwift(f.ID, scenarios)
		block = append(block, scenarioLines(f.ID, scenarios)...)
	}
	block = append(block, scenarioBlockEnd)
	files[scenarioManifest], err = spliceScenarioBlock(string(manifest), strings.Join(block, "\n")+"\n")
	return files, err
}

func readBuiltFlows(repo fs.FS) (map[string]bool, error) {
	rows, problems := flows.ReadApp(repo)
	if len(problems) > 0 {
		return nil, errs.New(errs.CodeInvalidInput, "monacoctl.readBuiltFlows: "+problems[0].String())
	}
	built := map[string]bool{}
	for _, r := range rows {
		built[r.ID] = r.Status.AtLeastBuilt()
	}
	return built, nil
}

func readFlowsTSV(repo fs.FS) ([]flows.Flow, error) {
	parsed, problems, err := readFlows(repo)
	if err == nil && len(problems) > 0 {
		err = errs.New(errs.CodeInvalidInput, "monacoctl.readFlowsTSV: "+problems[0].String())
	}
	return parsed, err
}

func writeFlowFiles(root string, files map[string]string) error {
	dir, err := os.OpenRoot(root)
	if err != nil {
		return errs.Wrap(err, errs.CodeInvalidInput, "monacoctl.writeFlowFiles")
	}
	defer func() { _ = dir.Close() }()
	if err := dir.MkdirAll(flowsSwiftDir, 0o750); err != nil {
		return errs.Wrap(err, errs.CodeInternal, "monacoctl.writeFlowFiles")
	}
	for name, body := range files {
		if err := dir.WriteFile(name, []byte(body), 0o600); err != nil {
			return errs.Wrap(err, errs.CodeInternal, "monacoctl.writeFlowFiles")
		}
	}
	return pruneFlowsSwift(dir, files)
}

func pruneFlowsSwift(dir *os.Root, keep map[string]string) error {
	entries, _ := fs.ReadDir(dir.FS(), flowsSwiftDir)
	for _, e := range entries {
		name := path.Join(flowsSwiftDir, e.Name())
		if _, kept := keep[name]; flowSwiftFile.MatchString(e.Name()) && !kept {
			if err := dir.Remove(name); err != nil {
				return errs.Wrap(err, errs.CodeInternal, "monacoctl.pruneFlowsSwift")
			}
		}
	}
	return nil
}

type swiftOutcome struct {
	name string
	code string
}

func flowOutcomes(f flows.Flow) ([]swiftOutcome, error) {
	codes := map[string]errs.Code{}
	for _, c := range errs.All() {
		codes[errs.Name(c)] = c
	}
	var (
		out         []swiftOutcome
		interrupted bool
	)
	for _, o := range f.Outcomes {
		if _, crash := o.CrashPoint(); crash {
			interrupted = true
			continue
		}
		if o == flows.OutcomeOK {
			out = append(out, swiftOutcome{name: "ok"})
			continue
		}
		code, ok := codes[string(o)]
		if !ok {
			return nil, errs.New(errs.CodeInvalidInput,
				fmt.Sprintf("monacoctl.flowOutcomes: flow %s outcome %s is not an errs code name", f.ID, o))
		}
		out = append(out, swiftOutcome{name: flowCaseName(string(o)), code: string(code)})
	}
	if interrupted {
		out = append(out, swiftOutcome{name: "interrupted"})
	}
	return out, nil
}

func flowCaseName(outcome string) string {
	name := strings.ToLower(outcome[:1]) + outcome[1:]
	if isSwiftKeyword(name) {
		return "`" + name + "`"
	}
	return name
}

func renderFlowSwift(f flows.Flow, outcomes []swiftOutcome) string {
	var b strings.Builder
	b.WriteString(flowsSwiftHeader + "\n")
	b.WriteString("public enum Flow" + f.ID + "Outcome: Sendable, Hashable, CaseIterable {\n")
	writeSwiftCaseList(&b, outcomes)
	b.WriteString("\n    public static let flowID = " + swiftString(f.ID) + "\n")
	commands := make([]string, len(f.Commands))
	for i, c := range f.Commands {
		commands[i] = swiftString(c)
	}
	b.WriteString("    public static let commands: [String] = [" + strings.Join(commands, ", ") + "]\n")
	b.WriteString("\n    public var code: String? {\n        switch self {\n")
	var silent []string
	for _, o := range outcomes {
		if o.code == "" {
			silent = append(silent, "."+o.name)
		}
	}
	if len(silent) > 0 {
		b.WriteString("        case " + strings.Join(silent, ", ") + ": nil\n")
	}
	for _, o := range outcomes {
		if o.code != "" {
			b.WriteString("        case ." + o.name + ": " + swiftString(o.code) + "\n")
		}
	}
	b.WriteString("        }\n    }\n\n    public init?(code: String) {\n        switch code {\n")
	for _, o := range outcomes {
		if o.code != "" {
			b.WriteString("        case " + swiftString(o.code) + ": self = ." + o.name + "\n")
		}
	}
	b.WriteString("        default: return nil\n        }\n    }\n}\n")
	return b.String()
}

func writeSwiftCaseList(b *strings.Builder, outcomes []swiftOutcome) {
	line := "    case"
	for i, o := range outcomes {
		item := " " + o.name
		if i < len(outcomes)-1 {
			item += ","
		}
		if len(line)+len(item) > swiftLineWidth {
			b.WriteString(line + "\n")
			line = "        "
			item = strings.TrimPrefix(item, " ")
		}
		line += item
	}
	b.WriteString(line + "\n")
}

func swiftString(s string) string { return `"` + s + `"` }

func renderFlowScenariosSwift(id string, scenarios []swiftOutcome) string {
	enum := "Flow" + id + "Scenario"
	var b strings.Builder
	b.WriteString(scenariosHeader + "\n")
	b.WriteString("public enum " + enum + ": String, CaseIterable, Sendable {\n")
	writeSwiftCaseList(&b, scenarios)
	b.WriteString("\n    /// The scenario that `" + scenarioLaunchFlag + " " + id +
		" <case>` names in the launch arguments.\n")
	b.WriteString("    public static func matching(_ arguments: [String]) -> " + enum + "? {\n")
	b.WriteString("        guard let flag = arguments.firstIndex(of: " + swiftString(scenarioLaunchFlag) + "),\n")
	b.WriteString("            arguments.indices.contains(flag + 2),\n")
	b.WriteString("            arguments[flag + 1] == " + swiftString(id) + "\n")
	b.WriteString("        else { return nil }\n")
	b.WriteString("        return " + enum + "(rawValue: arguments[flag + 2])\n    }\n}\n")
	return b.String()
}

func scenarioLines(id string, scenarios []swiftOutcome) []string {
	lines := make([]string, 0, len(scenarios))
	for _, s := range scenarios {
		value := strings.Trim(s.name, "`")
		name := "flow-" + id + "-" + kebab(value)
		lines = append(lines, fmt.Sprintf("%-*s %s %s %s", scenarioNameColumns-1, name, scenarioLaunchFlag, id, value))
	}
	return lines
}

func kebab(camel string) string {
	var b strings.Builder
	for _, r := range camel {
		if unicode.IsUpper(r) {
			b.WriteByte('-')
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}

func spliceScenarioBlock(manifest, block string) (string, error) {
	begin := strings.Index(manifest, scenarioBlockBegin+"\n")
	end := strings.Index(manifest, scenarioBlockEnd+"\n")
	switch {
	case begin < 0 && end < 0:
		if manifest != "" && !strings.HasSuffix(manifest, "\n\n") {
			manifest = strings.TrimSuffix(manifest, "\n") + "\n\n"
		}
		return manifest + block, nil
	case begin < 0 || end < begin:
		return "", errs.New(errs.CodeInvalidInput, fmt.Sprintf(
			"monacoctl.spliceScenarioBlock: %s needs %q before %q, each on its own line",
			scenarioManifest, scenarioBlockBegin, scenarioBlockEnd))
	}
	return manifest[:begin] + block + manifest[end+len(scenarioBlockEnd)+1:], nil
}

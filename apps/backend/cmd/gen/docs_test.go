func TestEventCatalogListsEachEventWithItsFields(t *testing.T) {
	t.Parallel()
	page := eventCatalog([]events.Entry{
		{
			Type: "widget.bumped", Subject: "events.widget.bumped", Version: 2,
			Fields: []events.Field{{Name: "v", GoType: "int"}, {Name: "n", GoType: "int"}},
		},
		{
			Type: "widget.ticked", Subject: "widget.ticked", Core: true, Version: 1,
			Fields: []events.Field{{Name: "v", GoType: "int"}, {Name: "as_of", GoType: "time.Time"}},
		},
	})
	want := "## `widget.bumped`\n\nSubject `events.widget.bumped`, version 2.\n\n" +
		"| Field | Go type |\n| --- | --- |\n| `v` | `int` |\n| `n` | `int` |\n\n" +
		"## `widget.ticked`\n\nCore NATS subject `widget.ticked`, version 1, never stored.\n\n" +
		"| Field | Go type |\n| --- | --- |\n| `v` | `int` |\n| `as_of` | `time.Time` |\n"
	if page != want {
		t.Fatalf("eventCatalog =\n%s\nwant\n%s", page, want)
	}
}

func TestGenDocsWritesTheEventErrorAndLogPages(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	if err := genDocs(dir); err != nil {
		t.Fatal(err)
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = root.Close() }()
	read := func(name string) string {
		body, err := root.ReadFile(name)
		if err != nil {
			t.Fatal(err)
		}
		return string(body)
	}
	const stamp = "Do not edit; run `go generate ./...` from `apps/backend`.\n\n"
	for name, want := range map[string][]string{
		"events.md": {"# Event catalog\n\nGenerated by `cmd/gen docs` from the `internal/events` registry. " + stamp},
		"errors.md": {
			"# Error codes\n\nGenerated by `cmd/gen docs` from the `internal/errs` code table. " + stamp +
				"| Code | HTTP status | Retryable | Alerts | Message |\n| --- | --- | --- | --- | --- |\n",
			"| `db_unavailable` | 503 | yes | no | The service is temporarily unavailable. Try again shortly. |\n",
			"| `panic` | 500 | no | yes | Something went wrong. |\n",
		},
		"logs.md": {
			"# Log messages\n\nGenerated by `cmd/gen docs` from the `internal/platform/observability` message registry. " +
				stamp + "| Message | Required attrs |\n",
			"| `boot.stopped` | `service`, `err` |\n",
		},
	} {
		page := read(name)
		if !strings.HasPrefix(page, want[0]) {
			t.Errorf("%s =\n%s\nwant prefix %q", name, page, want[0])
		}
		for _, line := range want[1:] {
			if !strings.Contains(page, line) {
				t.Errorf("%s lacks %q", name, line)
			}
		}
	}
	if rows := strings.Count(read("errors.md"), "\n| `"); rows != len(errs.All()) {
		t.Errorf("errors.md has %d code rows, want %d", rows, len(errs.All()))
	}
}

func TestGenDocsFailsWithoutAWritableDir(t *testing.T) {
	t.Parallel()
	if err := genDocs(filepath.Join(t.TempDir(), "gone")); err == nil || !strings.Contains(err.Error(), docsOp) {
		t.Fatalf("missing dir: genDocs = %v", err)
	}
	dir := t.TempDir()
	if err := os.Mkdir(filepath.Join(dir, "logs.md"), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := genDocs(dir); err == nil || !strings.Contains(err.Error(), docsOp+": internal") {
		t.Fatalf("logs.md is a directory: genDocs = %v", err)
	}
}

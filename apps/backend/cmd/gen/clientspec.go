package main

import (
	"os"
	"path/filepath"
	"regexp"

	"github.com/monaco/monaco/apps/backend/internal/errs"
)

const (
	clientSpecIn     = "api/openapi.yaml"
	clientSpecOut    = "../../packages/mobile-core/Sources/MonacoAPI/openapi.yaml"
	clientSpecHeader = "# Code generated by cmd/gen clientspec from api/openapi.yaml with the closed-object rule (additionalProperties off) removed. DO NOT EDIT.\n"
	clientSpecOp     = "gen.clientSpec"
)

var (
	strictBlockLine = regexp.MustCompile(`(?m)^[ \t]*additionalProperties: false\n`)
	strictFlowKey   = regexp.MustCompile(`additionalProperties: false, |, additionalProperties: false`)
)

func clientSpec(bundle []byte) []byte {
	lenient := strictBlockLine.ReplaceAll(bundle, nil)
	lenient = strictFlowKey.ReplaceAll(lenient, nil)
	return append([]byte(clientSpecHeader), lenient...)
}

func genClientSpec(in, out string) error {
	src, err := os.OpenRoot(filepath.Dir(in))
	if err != nil {
		return errs.Wrap(err, errs.CodeInvalidInput, clientSpecOp)
	}
	defer func() { _ = src.Close() }()
	bundle, err := src.ReadFile(filepath.Base(in))
	if err != nil {
		return errs.Wrap(err, errs.CodeInvalidInput, clientSpecOp)
	}
	dir, err := os.OpenRoot(filepath.Dir(out))
	if err != nil {
		return errs.Wrap(err, errs.CodeInvalidInput, clientSpecOp)
	}
	defer func() { _ = dir.Close() }()
	if err := dir.WriteFile(filepath.Base(out), clientSpec(bundle), 0o600); err != nil {
		return errs.Wrap(err, errs.CodeInternal, clientSpecOp)
	}
	return nil
}

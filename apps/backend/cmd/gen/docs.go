package main

import (
	"fmt"
	"os"
	"strings"

	"github.com/monaco/monaco/apps/backend/internal/errs"
	"github.com/monaco/monaco/apps/backend/internal/events"
	"github.com/monaco/monaco/apps/backend/internal/platform/observability"
)

const docsOp = "gen.docs"

func genDocs(refDir string) error {
	var logs strings.Builder
	_ = observability.WriteCatalog(&logs)
	dir, err := os.OpenRoot(refDir)
	if err != nil {
		return errs.Wrap(err, errs.CodeInvalidInput, docsOp)
	}
	defer func() { _ = dir.Close() }()
	for name, page := range map[string]string{
		"events.md": docsPage("Event catalog", "the `internal/events` registry", eventCatalog(events.Catalog())),
		"errors.md": docsPage("Error codes", "the `internal/errs` code table", errorTable(errs.All())),
		"logs.md":   docsPage("Log messages", "the `internal/platform/observability` message registry", logs.String()),
	} {
		if err := dir.WriteFile(name, []byte(page), 0o600); err != nil {
			return errs.Wrap(err, errs.CodeInternal, docsOp)
		}
	}
	return nil
}

func docsPage(title, source, body string) string {
	return fmt.Sprintf(
		"# %s\n\nGenerated by `cmd/gen docs` from %s. Do not edit; run `go generate ./...` from `apps/backend`.\n\n%s",
		title,
		source,
		body,
	)
}

func eventCatalog(entries []events.Entry) string {
	var b strings.Builder
	for i, e := range entries {
		if i > 0 {
			b.WriteString("\n")
		}
		lead, tail := "Subject", "."
		if e.Core {
			lead, tail = "Core NATS subject", ", never stored."
		}
		fmt.Fprintf(&b, "## `%s`\n\n%s `%s`, version %d%s\n\n| Field | Go type |\n| --- | --- |\n",
			e.Type, lead, e.Subject, e.Version, tail)
		for _, f := range e.Fields {
			fmt.Fprintf(&b, "| `%s` | `%s` |\n", f.Name, f.GoType)
		}
	}
	return b.String()
}

func errorTable(codes []errs.Code) string {
	yesNo := map[bool]string{true: "yes", false: "no"}
	var b strings.Builder
	b.WriteString("| Code | HTTP status | Retryable | Alerts | Message |\n| --- | --- | --- | --- | --- |\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "| `%s` | %d | %s | %s | %s |\n",
			c, errs.HTTPStatus(errs.KindOf(c)), yesNo[errs.Retryable(c)], yesNo[errs.Alert(c)], errs.Message(c))
	}
	return b.String()
}

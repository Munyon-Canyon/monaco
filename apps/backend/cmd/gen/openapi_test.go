const bundleBase = `openapi: 3.1.0
info:
  title: T
paths: {}
components:
  schemas:
    Problem:
      type: object
`

func writeSpecDir(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func specModule(file, path, schema string) string {
	return "paths:\n  " + path + ":\n    get:\n      operationId: op" + schema + "\n" +
		"      tags: [" + strings.TrimSuffix(file, ".yaml") + "]\n" +
		"components:\n  schemas:\n    " + schema + ":\n      type: string\n"
}

func TestBundleOpenAPI_mergesEverySpecFileInSortedOrder(t *testing.T) {
	t.Parallel()
	dir := writeSpecDir(t, map[string]string{
		"base.yaml":    bundleBase,
		"cabal.yaml":   specModule("cabal.yaml", "/v1/cabals", "Cabal"),
		"market.yaml":  specModule("market.yaml", "/v1/assets", "Asset"),
		"trading.yaml": specModule("trading.yaml", "/v1/orders", "Order"),
	})
	got, err := bundleOpenAPI(dir, nil)
	if err != nil {
		t.Fatal(err)
	}
	want := `# Code generated by cmd/gen openapi from api/spec/*.yaml. DO NOT EDIT.
openapi: 3.1.0
info:
  title: T
paths:
  # api/spec/cabal.yaml
  /v1/cabals:
    get:
      operationId: opCabal
      tags: [cabal]
  # api/spec/market.yaml
  /v1/assets:
    get:
      operationId: opAsset
      tags: [market]
  # api/spec/trading.yaml
  /v1/orders:
    get:
      operationId: opOrder
      tags: [trading]
components:
  schemas:
  # api/spec/base.yaml
    Problem:
      type: object
  # api/spec/cabal.yaml
    Cabal:
      type: string
  # api/spec/market.yaml
    Asset:
      type: string
  # api/spec/trading.yaml
    Order:
      type: string
`
	if string(got) != want {
		t.Fatalf("bundle =\n%s\nwant\n%s", got, want)
	}
}

func TestBundleOpenAPI_isStable(t *testing.T) {
	t.Parallel()
	dir := writeSpecDir(t, map[string]string{
		"base.yaml": bundleBase, "b.yaml": specModule("b.yaml", "/b", "B"), "a.yaml": specModule("a.yaml", "/a", "A"),
	})
	first, err := bundleOpenAPI(dir, nil)
	if err != nil {
		t.Fatal(err)
	}
	for range 5 {
		again, err := bundleOpenAPI(dir, nil)
		if err != nil || string(again) != string(first) {
			t.Fatalf("bundle changed between runs (%v):\n%s\nvs\n%s", err, first, again)
		}
	}
}


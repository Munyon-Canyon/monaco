func TestBundleOpenAPI_refusesSpecsItCannotBundle(t *testing.T) {
	t.Parallel()
	for name, tc := range map[string]struct {
		files map[string]string
		want  string
	}{
		"no base":           {map[string]string{"a.yaml": specModule("a.yaml", "/a", "A")}, "base.yaml"},
		"extra top key":     {map[string]string{"base.yaml": bundleBase, "a.yaml": "servers: []\n"}, `top-level key "servers"`},
		"bad indent":        {map[string]string{"base.yaml": bundleBase, "a.yaml": "paths:\n    /a:\n      get: {}\n"}, "indented 2 spaces"},
		"flow style paths":  {map[string]string{"base.yaml": bundleBase, "a.yaml": "paths: {/a: {get: {}}}\n"}, "block style"},
		"invalid yaml":      {map[string]string{"base.yaml": bundleBase, "a.yaml": "paths: [\n"}, "a.yaml"},
		"base lacks paths":  {map[string]string{"base.yaml": "openapi: 3.1.0\n"}, "paths and components"},
		"empty file":        {map[string]string{"base.yaml": bundleBase, "a.yaml": ""}, "mapping at the top level"},
		"list at the top":   {map[string]string{"base.yaml": bundleBase, "a.yaml": "- x\n"}, "mapping at the top level"},
		"components scalar": {map[string]string{"base.yaml": bundleBase, "a.yaml": "components: 3\n"}, "components must be a mapping"},
		"components kind bad indent": {
			map[string]string{"base.yaml": bundleBase, "a.yaml": "components:\n    schemas:\n      X:\n        type: string\n"},
			"components.schemas must be indented two spaces",
		},
		"operation tagged for another module": {
			map[string]string{"base.yaml": bundleBase, "a.yaml": "paths:\n  /a:\n    post:\n      tags: [b]\n"},
			"a.yaml: post /a has tags [b], want [a]",
		},
		"operation without a tag": {
			map[string]string{"base.yaml": bundleBase, "a.yaml": "paths:\n  /a:\n    get: {}\n"},
			"a.yaml: get /a has tags [], want [a]",
		},
		"operation that is not a mapping": {
			map[string]string{"base.yaml": bundleBase, "a.yaml": "paths:\n  /a:\n    get: x\n"},
			"a.yaml: get /a has tags [], want [a]",
		},
		"paths scalar": {map[string]string{"base.yaml": bundleBase, "a.yaml": "paths: 3\n"}, "path entries must be a mapping"},
		"anyOf with a null branch": {
			map[string]string{
				"base.yaml": bundleBase,
				"a.yaml": "components:\n  schemas:\n    A:\n      type: object\n      properties:\n" +
					"        me: {anyOf: [{$ref: \"#/components/schemas/B\"}, {type: \"null\"}]}\n",
			},
			"a.yaml:6: a null branch in anyOf or oneOf",
		},
		"oneOf with a null branch": {
			map[string]string{
				"base.yaml": bundleBase,
				"a.yaml": "components:\n  schemas:\n    A:\n      oneOf:\n        - plain\n        - $ref: \"#/components/schemas/B\"\n" +
					"        - type: \"null\"\n",
			},
			"a.yaml:4: a null branch in anyOf or oneOf",
		},
		"duplicate in an unlisted kind": {
			map[string]string{
				"base.yaml": bundleBase,
				"a.yaml":    "components:\n  examples:\n    Ex:\n      value: 1\n",
				"b.yaml":    "components:\n  examples:\n    Ex:\n      value: 2\n",
			},
			"examples Ex is defined in both a.yaml and b.yaml",
		},
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			_, err := bundleOpenAPI(writeSpecDir(t, tc.files), nil)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("err = %v, want it to contain %q", err, tc.want)
			}
		})
	}
}


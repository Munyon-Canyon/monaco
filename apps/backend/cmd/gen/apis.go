package main

import (
	"errors"
	"io/fs"
	"maps"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"

	"github.com/monaco/monaco/apps/backend/internal/errs"
)

const (
	moduleSpecPath = "spec.yaml"
	apiPkgSuffix   = "api"
	apiAllPkg      = "apiall"
	genFile        = "api.gen.go"
	mountGenFile   = "mount.gen.go"
	apisOp         = "gen.genAPIs"
	apisHeader     = "// Code generated by cmd/gen httpapi from api/spec/*.yaml. DO NOT EDIT."

	mountTemplate = apisHeader + `

package {{pkg}}

import "{{base}}"

func Mount(ssi StrictServerInterface, m api.Mount, strict ...StrictMiddlewareFunc) {
	mws := make([]MiddlewareFunc, 0, len(m.Middlewares))
	for _, mw := range m.Middlewares {
		mws = append(mws, mw)
	}
	HandlerWithOptions(NewStrictHandlerWithOptions(ssi, strict, StrictHTTPServerOptions{
		RequestErrorHandlerFunc:  m.InvalidRequest,
		ResponseErrorHandlerFunc: m.Problem,
	}), StdHTTPServerOptions{
		BaseRouter:       m.Mux,
		ErrorHandlerFunc: m.InvalidRequest,
		Middlewares:      mws,
	})
}
`

	apiAllTemplate = apisHeader + `

package apiall

import (
	"context"
	"net/http"

	"{{base}}"
{{imports}})

func DecodeOnly(m api.Mount) {
	decoded := func(context.Context, http.ResponseWriter, *http.Request, any) (any, error) { return nil, nil }
{{mounts}}}
`

	apiAllMount = `	{{pkg}}.Mount(struct {
		{{pkg}}.StrictServerInterface
	}{}, m, func({{pkg}}.StrictHandlerFunc, string) {{pkg}}.StrictHandlerFunc { return decoded })
`
)

var (
	componentRef    = regexp.MustCompile(`#/components/(\w+)/([\w.-]+)`)
	generatedHeader = regexp.MustCompile(`(?m)^// Code generated by .* DO NOT EDIT\.$`)
	enumAlignment   = regexp.MustCompile(`(?m)^(\t\w+) +(\w+) = `)
)

type apiSpecs struct {
	b       bundler
	modules []string
}

func genAPIs(specDir, outDir, baseImport string, codes []errs.Code) error {
	specs, err := loadAPISpecs(specDir, codes)
	if err != nil {
		return err
	}
	files, err := specs.generate(baseImport)
	if err != nil {
		return err
	}
	out, err := os.OpenRoot(outDir)
	if err != nil {
		return errs.Wrap(err, errs.CodeInvalidInput, apisOp)
	}
	defer func() { _ = out.Close() }()
	for _, name := range slices.Sorted(maps.Keys(files)) {
		if err := out.MkdirAll(filepath.Dir(name), 0o750); err != nil {
			return errs.Wrap(err, errs.CodeInternal, apisOp)
		}
		if err := out.WriteFile(name, []byte(files[name]), 0o600); err != nil {
			return errs.Wrap(err, errs.CodeInternal, apisOp)
		}
	}
	return removeStalePackages(out, specs.packages())
}

func loadAPISpecs(specDir string, codes []errs.Code) (*apiSpecs, error) {
	root, err := os.OpenRoot(specDir)
	if err != nil {
		return nil, errs.Wrap(err, errs.CodeInvalidInput, apisOp)
	}
	defer func() { _ = root.Close() }()
	names, _ := fs.Glob(root.FS(), "*.yaml")
	if !slices.Contains(names, baseSpec) {
		return nil, specProblem("%s has no %s", specDir, baseSpec)
	}
	slices.Sort(names)
	s := &apiSpecs{}
	for _, name := range slices.Concat([]string{baseSpec}, slices.DeleteFunc(names, func(n string) bool { return n == baseSpec })) {
		src, err := root.ReadFile(name)
		if err != nil {
			return nil, errs.Wrap(err, errs.CodeInvalidInput, apisOp)
		}
		if err := s.b.add(name, string(src)); err != nil {
			return nil, err
		}
		if !isBaseFile(name) {
			s.modules = append(s.modules, name)
		}
	}
	if err := s.b.add(errorCodesSpec, renderErrorCodes(codes)); err != nil {
		return nil, err
	}
	return s, nil
}

func isBaseFile(file string) bool { return file == baseSpec || file == errorCodesSpec }

func (s *apiSpecs) packages() []string {
	pkgs := make([]string, 0, len(s.modules))
	for _, file := range s.modules {
		pkgs = append(pkgs, strings.TrimSuffix(file, ".yaml")+apiPkgSuffix)
	}
	return pkgs
}

func (s *apiSpecs) generate(baseImport string) (map[string]string, error) {
	base := s.baseSpec()
	code, err := oapiGenerate(base, base, "api", codegen.GenerateOptions{Models: true}, nil)
	if err != nil {
		return nil, err
	}
	files := map[string]string{genFile: enumAlignment.ReplaceAllString(code, "$1 $2 = ")}
	var imports, mounts strings.Builder
	for i, pkg := range s.packages() {
		mini, err := s.moduleSpec(s.modules[i])
		if err != nil {
			return nil, err
		}
		code, err := oapiGenerate(base, mini, pkg,
			codegen.GenerateOptions{StdHTTPServer: true, Strict: true, Models: true},
			map[string]string{baseSpec: baseImport})
		if err != nil {
			return nil, err
		}
		fill := strings.NewReplacer("{{pkg}}", pkg, "{{base}}", baseImport)
		files[filepath.Join(pkg, genFile)] = code
		files[filepath.Join(pkg, mountGenFile)] = fill.Replace(mountTemplate)
		imports.WriteString("\t\"" + baseImport + "/" + pkg + "\"\n")
		mounts.WriteString(fill.Replace(apiAllMount))
	}
	files[filepath.Join(apiAllPkg, apiAllPkg+".gen.go")] = strings.NewReplacer(
		"{{base}}", baseImport, "{{imports}}", imports.String(), "{{mounts}}", mounts.String(),
	).Replace(apiAllTemplate)
	return files, nil
}

func oapiGenerate(base, spec, pkg string, gen codegen.GenerateOptions, mapping map[string]string) (string, error) {
	loader := openapi3.NewLoader()
	loader.IncludeOrigin = true
	loader.ReadFromURIFunc = func(_ *openapi3.Loader, u *url.URL) ([]byte, error) {
		if u.Path != baseSpec {
			return nil, specProblem("%s refs %s; a spec file refs only its own components and %s", pkg, u, baseSpec)
		}
		return []byte(base), nil
	}
	doc, err := loader.LoadFromDataWithPath([]byte(spec), &url.URL{Path: moduleSpecPath})
	if err != nil {
		return "", specProblem("%s: %v", pkg, err)
	}
	code, err := codegen.Generate(doc, codegen.Configuration{
		PackageName:   pkg,
		Generate:      gen,
		OutputOptions: codegen.OutputOptions{SkipPrune: true},
		ImportMapping: mapping,
	}.UpdateDefaults())
	if err != nil {
		return "", specProblem("oapi-codegen %s: %v", pkg, err)
	}
	return generatedHeader.ReplaceAllLiteralString(code, apisHeader), nil
}

func (s *apiSpecs) header() []string {
	var out []string
	for _, key := range s.b.order {
		if key != "paths" && key != "components" {
			out = append(out, s.b.raw[key]...)
		}
	}
	return out
}

func (s *apiSpecs) baseSpec() string {
	out := append(s.header(), "paths: {}", "components:")
	out = append(out, s.components(isBaseFile)...)
	return strings.Join(out, "\n") + "\n"
}

func (s *apiSpecs) moduleSpec(file string) (string, error) {
	own := func(f string) bool { return f == file }
	out := s.header()
	if paths := entriesOf(&s.b.paths, own); len(paths) > 0 {
		out = append(append(out, "paths:"), paths...)
	} else {
		out = append(out, "paths: {}")
	}
	out = append(append(out, "components:"), s.components(own)...)
	var refErr error
	for i, line := range out {
		out[i] = componentRef.ReplaceAllStringFunc(line, func(ref string) string {
			m := componentRef.FindStringSubmatch(ref)
			owner := s.owner(m[1], m[2])
			switch {
			case owner == "" || owner == file:
				return ref
			case isBaseFile(owner):
				return baseSpec + ref
			default:
				refErr = specProblem("%s refs %s %s, which %s defines; move it to %s", file,
					componentLabel(m[1]), m[2], owner, baseSpec)
				return ref
			}
		})
	}
	return strings.Join(out, "\n") + "\n", refErr
}

func (s *apiSpecs) owner(kind, name string) string {
	if g, ok := s.b.kinds[kind]; ok {
		return g.entries[name].file
	}
	return ""
}

func (s *apiSpecs) components(keep func(string) bool) []string {
	var out []string
	for _, kind := range s.b.kindList {
		if entries := entriesOf(s.b.kinds[kind], keep); len(entries) > 0 {
			out = append(append(out, "  "+kind+":"), entries...)
		}
	}
	if len(out) == 0 {
		return []string{"  schemas: {}"}
	}
	return out
}

func entriesOf(g *group, keep func(string) bool) []string {
	var out []string
	for _, key := range slices.Sorted(maps.Keys(g.entries)) {
		if keep(g.entries[key].file) {
			out = append(out, g.entries[key].lines...)
		}
	}
	return out
}

func removeStalePackages(out *os.Root, keep []string) error {
	dirs, _ := fs.Glob(out.FS(), "*"+apiPkgSuffix)
	failed := make([]error, 0, len(dirs))
	for _, dir := range slices.DeleteFunc(dirs, func(d string) bool { return slices.Contains(keep, d) }) {
		failed = append(failed, out.RemoveAll(dir))
	}
	return errors.Join(failed...)
}

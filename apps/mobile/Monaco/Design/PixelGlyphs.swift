import SwiftUI

extension MonacoIcon {
    func pixel(filled: Bool = false) -> PixelBitmap? {
        if filled, let solid = PixelGlyphs.filled[self] { return solid }
        return PixelGlyphs.outline[self]
    }

    var hasPixel: Bool { pixel() != nil }

    func tabImage(selected: Bool, scale: CGFloat) -> UIImage? {
        pixel(filled: selected)?.templateImage(pointSize: MonacoGlyphMetrics.tab, scale: scale)
    }

    init?(systemName: String) {
        guard let match = MonacoIcon.allCases.first(where: { $0.symbol == systemName || $0.filled == systemName })
        else { return nil }
        self = match
    }
}

